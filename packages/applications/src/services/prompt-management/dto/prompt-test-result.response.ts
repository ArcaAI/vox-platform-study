import { ApiProperty } from '@nestjs/swagger';

/**
 * TASK-328 A4 — result of a prompt quality/score test run.
 *
 * Returned by `POST /admin/prompt-templates/:id/test`. The `version` is the
 * row's new `_version` after the score/output were persisted (the test run is
 * an OCC write), so the client can keep editing without a re-fetch.
 */
export class PromptTestResultResponse {
  @ApiProperty({ description: 'Prompt template ID' })
  id: string;

  @ApiProperty({ description: 'Quality score in the range [0, 1]', example: 0.92 })
  score: number;

  @ApiProperty({ description: 'Text generated by the SMR/text-generation service' })
  output: string;

  @ApiProperty({ description: 'Timestamp of the test run (ISO 8601)' })
  testedAt: string;

  @ApiProperty({ description: 'Row version after persisting the test result (OCC token)', example: 8 })
  version: number;
}
