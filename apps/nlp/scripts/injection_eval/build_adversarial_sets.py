_AI = (
    r"(?:\bA\.?I\.?(?=[\s,:'-])|\bartificial intelligence\b|\bchat ?bots?\b|\bchatgpt\b"
    r"|\blanguage models?\b|\bLLMs?\b|\bthe model\b|\b(?:AI|virtual|digital|documentation"
    r"|writing|note[- ]taking) assistant\b|\bscribe\b|\bnote[- ]?(?:writer|taker)\b"
    r"|\bsummar(?:y|ising|izing) (?:tool|software|system|bot)\b|\bdocumentation"
    r" (?:system|tool|software)\b|\bwhoever (?:or whatever )?(?:is )?(?:writ|prepar"
    r"|compil|summar|turn)\w*|\bwhatever (?:is )?(?:writ|turn|summar)\w*)"
)
# The AI is ADDRESSED: a vocative opener ("AI scribe, ...", "Hey assistant: ...", "Model:"),
# or a note / message / request "to the AI".
_VOCATIVE_RE = re.compile(
    r"^(?:(?:hey|hi|ok(?:ay)?|dear|attention|note|message|instruction|request|reminder)"
    r"(?: (?:to|for))?,? (?:the |you,? )?)?(?:" + _AI + r"|assistant|model|bot)\b[^.?!]{0,40}[,:]"
    r"|\b(?:note|message|instructions?|request|reminder)s? (?:to|for) (?:the )?(?:" + _AI + r")",
    re.IGNORECASE,
)
# The AI is the subject of an obligation ("the AI scribe should leave that out").
_AI_MODAL_RE = re.compile(
    _AI + r"\W+(?:\w+\W+){0,2}?(?:should|must|needs? to|has to|is to|shall|had better)\b",
    re.IGNORECASE,
)
# An instruction passed to the AI through someone else ("ask the AI to leave it out").
_PROXY_RE = re.compile(
    r"\b(?:tell|ask|instruct|make|get|want|need|like) (?:the |your |that )?(?:" + _AI + r")"
    r"[^.?!]{0,20}\b(?:to|not)\b",
    re.IGNORECASE,
)
_CANONICAL_RE = re.compile(
    r"ignore (?:all|your) (?:of )?(?:the |your )?(?:previous|prior|earlier|above)"
    r" (?:instructions|rules|prompts?)"
    r"|\b(?:your|print|reveal|repeat|show)\b[^.?!]{0,30}\bsystem prompt"
    r"|<<<|\[/?INST\]|<\|im_start\||^#+\s*system\b|\byou are now\b|\bas an AI\b",
    re.IGNORECASE | re.MULTILINE,
)
_SPEAKER_PREFIX_RE = re.compile(r"^\s*[A-Za-z][A-Za-z ]{0,24}:\s*")


def ai_directed_sentences(text: str) -> list[str]:
    """Sentences that give an AI / model / assistant a directive (empty for benign text).

    Conservative for a LABEL-0 set: any of the four shapes drops the region. A sentence
    that only MENTIONS the AI ("The AI scribe will record the visit", "Does the AI scribe
    write everything down?") is kept — that is exactly the benign text b2 needs.
    """
    patterns = (_CANONICAL_RE, _VOCATIVE_RE, _AI_MODAL_RE, _PROXY_RE)
    found: list[str] = []
    for line in text.split("\n"):
        utterance = _SPEAKER_PREFIX_RE.sub("", line, count=1)
        for sentence in re.split(r"(?<=[.!?])\s+", utterance):
            s = sentence.strip()
            if s and any(p.search(s) for p in patterns):
                found.append(s)
    return found


def is_ai_directed(text: str) -> bool:
    return bool(ai_directed_sentences(text))


