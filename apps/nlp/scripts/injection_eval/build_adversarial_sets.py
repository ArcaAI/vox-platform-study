def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--lmstudio-root", default=DEFAULT_LMSTUDIO_ROOT)
    parser.add_argument("--workers", type=int, default=2)
    parser.add_argument("--timeout", type=float, default=900.0)
    parser.add_argument("--fresh", action="store_true", help="ignore <out>/b2_raw.jsonl")
    args = parser.parse_args(argv)

    out: Path = args.out
    out.mkdir(parents=True, exist_ok=True)
    prompts = json.loads(B2_PROMPTS_PATH.read_text(encoding="utf-8"))
    raw_path = out / "b2_raw.jsonl"
    cache = {}
    if raw_path.exists() and not args.fresh:
        cache = {
            entry["key"]: entry
            for entry in read_jsonl(raw_path)
            if entry.get("model") == APPROVED_MODEL
        }
    elif raw_path.exists():
        raw_path.unlink()
    dropped: list[dict] = []

    def on_raw(entry: dict) -> None:
        with raw_path.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(entry, ensure_ascii=False) + "\n")
        print(f"generated {entry['key']} ({len(entry['raw'])} chars)", flush=True)

    root = args.lmstudio_root
    complete = lmstudio_complete(
        f"{root.rstrip('/')}/v1",
        temperature=prompts["temperature"],
        max_tokens=prompts["max_tokens"],
        timeout=args.timeout,
    )
    b2, stats = generate_b2(
        prompts,
        complete,
        preflight=lambda: assert_model_loaded(root),
        cache=cache,
        on_raw=on_raw,
        on_drop=dropped.append,
        workers=args.workers,
    )
    write_jsonl(out / "b2_dropped.jsonl", dropped)
    payloads = load_payloads()
    c2 = build_c2(payloads, b2, load_golden_cases())
    write_jsonl(out / "b2.jsonl", b2)
    write_jsonl(out / "c2.jsonl", c2)
    manifest = build_manifest(out, b2, c2, stats, payloads)
    (out / "adversarial_sets_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(json.dumps({k: manifest[k]["records"] for k in ("b2", "c2")}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
