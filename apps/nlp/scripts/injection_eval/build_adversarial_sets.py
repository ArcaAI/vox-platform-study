def split_for(key: str) -> str:
    """30 / 70 dev / test, stable per key (c2 passes the PAYLOAD id)."""
    return "dev" if int(hashlib.sha1(key.encode()).hexdigest(), 16) % 10 < 3 else "test"


def _rng(*parts: str) -> random.Random:
    return random.Random(int(hashlib.sha256("|".join(parts).encode()).hexdigest(), 16))


def _count_windows(text: str) -> int:
    return sum(1 for _ in iter_windows(text, WINDOW_SIZE, WINDOW_OVERLAP))


