_CAREGIVER_WORDS = (
    "caregiver|carer|mother|father|mum|mom|dad|parent|son|daughter|wife|husband|relative"
)
_LABEL_RE = re.compile(
    r"^(?P<label>doctor|dr\.?(?: [A-Z][a-z]+)?|patient|nurse|attachment|" + _CAREGIVER_WORDS + r")"
    r"(?: \([^)]{0,30}\))?\s*:\s*(?P<body>.*)$",
    re.IGNORECASE,
)
_SEPARATOR_RE = re.compile(r"^[-=*_#~\s]+$")


def _canonical_label(raw: str) -> str:
    low = raw.lower()
    if low.startswith("dr") or low == "doctor":
        return "Doctor"
    if low in {"patient", "nurse", "attachment"}:
        return low.capitalize()
    return "Caregiver"


def normalize_generation(raw: str) -> str:
    """Model output → ``Speaker: text`` lines; preamble, markdown and trailers removed."""
    text = raw.replace("\r\n", "\n")
    text = re.sub(r"\*\*|__|`", "", text)
    lines: list[str] = []
    trailing: list[str] = []
    current = ""
    for line in text.split("\n"):
        s = re.sub(r"^[>\-*•\s]+", "", line.strip()).strip()
        if not s or _SEPARATOR_RE.match(s):
            continue
        match = _LABEL_RE.match(s)
        if match:
            body = match.group("body").strip().lstrip(":").strip()
            if not body:
                continue
            lines.extend(trailing)
            trailing = []
            current = _canonical_label(match.group("label"))
            lines.append(f"{current}: {body}")
        elif current == "Attachment" and not trailing:
            lines.append(f"Attachment: {s}")  # the next line of the same document
        elif lines:
            trailing.append(s)  # a continuation, kept only if another speaker line follows
    return "\n".join(lines)


def _trim_region(text: str, limit: int = REGION_MAX) -> str:
    if len(text) <= limit:
        return text
    kept: list[str] = []
    used = 0
    for line in text.split("\n"):
        if used + len(line) + (1 if kept else 0) > limit:
            break
        used += len(line) + (1 if kept else 0)
        kept.append(line)
    return "\n".join(kept)


