class ModelNotLoaded(RuntimeError):
    """The approved generator is not loaded in LM Studio: STOP (never trigger a JIT load)."""


def _get_json(url: str, timeout: float = 10.0) -> dict:
    with urllib.request.urlopen(url, timeout=timeout) as response:  # noqa: S310
        return json.loads(response.read())


def assert_model_loaded(
    root_url: str = DEFAULT_LMSTUDIO_ROOT,
    model: str = APPROVED_MODEL,
    *,
    fetch: Callable[[str], dict] = _get_json,
) -> None:
    """Raise `ModelNotLoaded` unless LM Studio reports `model` with state ``loaded``.

    Reads `GET <root>/api/v0/models` — a listing, which never loads anything.
    """
    listing = fetch(f"{root_url.rstrip('/')}/api/v0/models")
    states = {entry.get("id"): entry.get("state") for entry in listing.get("data", [])}
    if states.get(model) != "loaded":
        raise ModelNotLoaded(f"{model} is {states.get(model, 'absent')!r} in LM Studio, not loaded")


def _slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")


def _jobs(prompts: dict) -> list[dict]:
    jobs = []
    for scenario in prompts["scenarios"]:
        for specialty in scenario["specialties"]:
            for seed in scenario["seeds"]:
                jobs.append(
                    {
                        "key": f"b2-{scenario['id']}-{_slug(specialty)}-s{seed}",
                        "scenario": scenario["id"],
                        "specialty": specialty,
                        "seed": seed,
                        "messages": [
                            {"role": "system", "content": prompts["system"]},
                            {
                                "role": "user",
                                "content": scenario["prompt"].replace("{specialty}", specialty),
                            },
                        ],
                    }
                )
    return jobs


def generate_b2(
    prompts: dict,
    complete: Complete,
    *,
    model: str = APPROVED_MODEL,
    preflight: Callable[[], None] | None = None,
    cache: dict[str, dict] | None = None,
    on_raw: Callable[[dict], None] | None = None,
    on_drop: Callable[[dict], None] | None = None,
    workers: int = 1,
) -> tuple[list[dict], dict]:
    """Generate (or reuse cached) regions, normalise, filter → (b2 records, stats).

    Only `APPROVED_MODEL` may be used and there is NO fallback: any failure propagates.
    `preflight` runs before every batch (one batch = `workers` concurrent requests) and
    must raise to stop the run before a request is sent.
    """
    if model != APPROVED_MODEL:
        raise ValueError(f"only {APPROVED_MODEL} is approved for generation, not {model}")
    cache = dict(cache or {})
    jobs = _jobs(prompts)
    stats: Counter = Counter(requested=len(jobs))

    def run(job: dict) -> dict:
        raw = complete(model, job["messages"], job["seed"])
        entry = {k: job[k] for k in ("key", "scenario", "specialty", "seed")}
        entry.update(model=model, raw=raw)
        if on_raw is not None:
            on_raw(entry)
        return entry

    pending = [job for job in jobs if job["key"] not in cache]
    stats["cached"] = len(jobs) - len(pending)
    size = max(1, workers)
    with ThreadPoolExecutor(max_workers=size) as pool:
        for start in range(0, len(pending), size):
            if preflight is not None:
                preflight()
            for entry in pool.map(run, pending[start : start + size]):
                cache[entry["key"]] = entry

    records: list[dict] = []
    for job in jobs:
        entry = cache[job["key"]]
        text = _trim_region(normalize_generation(entry["raw"]))
        reasons = ["length"] if len(text) < REGION_MIN else quality_issues(text)
        if reasons:
            stats[f"dropped_{reasons[0]}"] += 1
            stats["dropped"] += 1
            if on_drop is not None:
                on_drop({"key": job["key"], "reasons": reasons, "text": text})
            continue
        records.append(
            {
                "id": job["key"],
                "set": "b2",
                "split": split_for(job["key"]),
                "label": 0,
                "text": text,
                "meta": {
                    "scenario": job["scenario"],
                    "specialty": job["specialty"],
                    "seed": job["seed"],
                    "model": entry["model"],
                    "trigger_terms": trigger_terms(text),
                },
            }
        )
    stats["kept"] = len(records)
    for reason in DROP_REASONS:
        stats.setdefault(f"dropped_{reason}", 0)
    stats.setdefault("dropped", 0)
    stats["drop_rate"] = round(stats["dropped"] / len(jobs), 4) if jobs else 0.0
    return records, dict(stats)


def lmstudio_complete(
    base_url: str, *, temperature: float, max_tokens: int, timeout: float
) -> Complete:
    """An OpenAI-compatible chat-completions caller (stdlib only), approved model ONLY."""

    def complete(model: str, messages: list[dict], seed: int) -> str:
        if model != APPROVED_MODEL:
            raise ValueError(f"refusing to call {model}: only {APPROVED_MODEL} is approved")
        body = json.dumps(
            {
                "model": model,
                "messages": messages,
                "temperature": temperature,
                "max_tokens": max_tokens,
                "seed": seed,
                "stream": False,
            }
        ).encode()
        request = urllib.request.Request(
            f"{base_url.rstrip('/')}/chat/completions",
            data=body,
            headers={"Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:  # noqa: S310
                payload = json.loads(response.read())
        except urllib.error.HTTPError as error:
            raise RuntimeError(f"{model}: HTTP {error.code} {error.read()[:300]!r}") from error
        content = payload["choices"][0]["message"].get("content") or ""
        if not content.strip():
            raise RuntimeError(f"{model}: empty completion")
        return content

    return complete


