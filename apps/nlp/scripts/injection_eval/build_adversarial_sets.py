def asr_noise(payload: str, rng: random.Random, *, keep_tokens: bool) -> str:
    """ASR-style damage: fillers, repeated words; lower case, no punctuation unless the
    payload's tokens ARE the attack (obfuscation, delimiter markup)."""
    out: list[str] = []
    for token in payload.split():
        if not keep_tokens:
            token = "".join(
                ch for ch in token.lower() if not unicodedata.category(ch).startswith("P")
            )
        if not token:
            continue
        out.append(token)
        roll = rng.random()
        if roll < 0.12:
            out.append(token)
        elif roll < 0.32:
            out.append(rng.choice(_ASR_FILLERS))
    return " ".join(out)


def _fit_lead_in(need: int) -> str:
    """Exactly `need` chars of spoken lead-in, ending in a space (extra spaces pad gaps)."""
    words: list[str] = []
    pool = _LEAD_IN.split()
    i = 0
    while True:
        word = pool[i % len(pool)]
        if sum(len(w) + 1 for w in words) + len(word) + 1 > need:
            break
        words.append(word)
        i += 1
    deficit = need - sum(len(w) + 1 for w in words)
    gaps = [" "] * len(words)
    for k in range(deficit):
        gaps[-1 - (k % len(gaps))] += " "
    return "".join(w + g for w, g in zip(words, gaps, strict=True))


def _base_pool(b2_records: list[dict], golden_cases: list[dict]) -> list[tuple[str, str]]:
    pool = [(f"golden:{case['caseId']}", render_golden_case(case)) for case in golden_cases]
    pool += [(f"b2:{record['id']}", record["text"]) for record in b2_records]
    return sorted(pool)


def _boundary_region(
    payload: str, pool: list[tuple[str, str]], rng: random.Random
) -> tuple[str, list[str], int]:
    """A region >= 4,000 chars where the payload starts one char before window 2."""
    ids: list[str] = []
    parts: list[str] = []
    while sum(len(p) for p in parts) < BOUNDARY_BASE_MIN:
        base_id, text = rng.choice(pool)
        if base_id in ids:
            continue
        ids.append(base_id)
        parts.append(text)
    lines = "\n".join(parts).split("\n")
    start = WINDOW_SIZE - WINDOW_OVERLAP - 1
    prefix = f"{rng.choice(['Caregiver', 'Patient'])}: "
    head: list[str] = []
    used = 0
    while lines and used + len(lines[0]) + 1 + len(prefix) + 40 <= start:
        line = lines.pop(0)
        head.append(line)
        used += len(line) + 1
    first = "\n".join(head) + ("\n" if head else "") + prefix
    first += _fit_lead_in(start - len(first))
    rest = _trim_region("\n".join(lines), BOUNDARY_REGION_MAX - start - len(payload))
    region = straddle_payload(
        first + "\n" + rest, payload, size=WINDOW_SIZE, overlap=WINDOW_OVERLAP
    )
    return region, ids, start


def build_c2(payloads: list[dict], b2_records: list[dict], golden_cases: list[dict]) -> list[dict]:
    """Every payload under five carriers; deterministic given the inputs."""
    pool = _base_pool(b2_records, golden_cases)
    records: list[dict] = []
    for payload in sorted(payloads, key=lambda p: p["id"]):
        pid, text = payload["id"], payload["text"]
        long_payload = len(text) > LONG_PAYLOAD
        carriers = [
            *SPEECH_CARRIERS,
            "attachment",
            "window_boundary" if long_payload else "asr_noise",
        ]
        for carrier in carriers:
            rng = _rng(pid, carrier)
            meta: dict = {
                "payload_id": pid,
                "class": payload["class"],
                "carrier": carrier,
                "lang": payload["lang"],
                "length_class": payload["length_class"],
            }
            if payload.get("origin") == "task1047_reconstruction":
                meta["note"] = (
                    "Reconstruction, in spirit, of one of the ten TASK-1047 §8.6 injections "
                    "embedded in clinical dialogue; the original set was not saved."
                )
            embedded = text
            if carrier == "window_boundary":
                region, base_ids, offset = _boundary_region(text, pool, rng)
                meta["base_id"] = "+".join(base_ids)
            else:
                base_id, base = rng.choice(pool)
                meta["base_id"] = base_id
                if carrier == "attachment":
                    kind, head, tail = ATTACHMENT_TEMPLATES[
                        rng.randrange(len(ATTACHMENT_TEMPLATES))
                    ]
                    meta["attachment"] = kind
                    block = head + text + tail
                    region = embed_payload(base, block, "", rng, max_chars=REGION_MAX)
                    offset = region.index(block) + len(head)
                else:
                    speaker = SPEECH_CARRIERS.get(carrier, "Patient")
                    if carrier == "asr_noise":
                        embedded = asr_noise(
                            text, rng, keep_tokens=payload["class"] in _KEEP_TOKENS
                        )
                        meta["embedded_text"] = embedded
                    region = embed_payload(base, embedded, speaker, rng, max_chars=REGION_MAX)
                    offset = region.index(f"{speaker}: {embedded}") + len(speaker) + 2
            meta["offset"] = offset
            assert region[offset : offset + len(embedded)] == embedded, (pid, carrier)
            records.append(
                {
                    "id": f"c2-{pid}-{carrier}",
                    "set": "c2",
                    "split": split_for(pid),
                    "label": 1,
                    "text": region,
                    "meta": meta,
                }
            )
    return records


# --- manifest ------------------------------------------------------------------------------


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _tally(records: list[dict], key: Callable[[dict], str]) -> dict:
    out: dict[str, dict[str, int]] = {}
    for record in records:
        bucket = out.setdefault(key(record), {"records": 0, "windows": 0})
        bucket["records"] += 1
        bucket["windows"] += _count_windows(record["text"])
    return dict(sorted(out.items()))


def build_manifest(
    out: Path, b2: list[dict], c2: list[dict], b2_stats: dict, payloads: list[dict]
) -> dict:
    def per_split_payloads() -> dict[str, int]:
        return dict(Counter(split_for(p["id"]) for p in payloads))

    return {
        "task": "TASK-1049",
        "lane": "L2",
        "geometry": {"size": WINDOW_SIZE, "overlap": WINDOW_OVERLAP},
        "files": {
            name: {"sha256": _sha256(out / name), "records": len(records)}
            for name, records in (("b2.jsonl", b2), ("c2.jsonl", c2))
        },
        "b2": {
            "label": 0,
            "records": len(b2),
            "windows": sum(_count_windows(r["text"]) for r in b2),
            "by_split": _tally(b2, lambda r: r["split"]),
            "by_scenario": _tally(b2, lambda r: r["meta"]["scenario"]),
            "by_specialty": _tally(b2, lambda r: r["meta"]["specialty"]),
            "models": dict(Counter(r["meta"]["model"] for r in b2)),
            "generation": b2_stats,
            "region_chars": {
                "min": min((len(r["text"]) for r in b2), default=0),
                "max": max((len(r["text"]) for r in b2), default=0),
            },
        },
        "c2": {
            "label": 1,
            "records": len(c2),
            "windows": sum(_count_windows(r["text"]) for r in c2),
            "payloads": len(payloads),
            "payloads_by_split": per_split_payloads(),
            "by_split": _tally(c2, lambda r: r["split"]),
            "by_class": _tally(c2, lambda r: r["meta"]["class"]),
            "by_carrier": _tally(c2, lambda r: r["meta"]["carrier"]),
            "by_lang": _tally(c2, lambda r: r["meta"]["lang"]),
            "by_split_class": _tally(c2, lambda r: f"{r['split']}/{r['meta']['class']}"),
            "by_split_carrier": _tally(c2, lambda r: f"{r['split']}/{r['meta']['carrier']}"),
        },
    }


