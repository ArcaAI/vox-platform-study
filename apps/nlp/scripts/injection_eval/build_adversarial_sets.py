def quality_issues(text: str) -> list[str]:
    """Why a normalised b2 region is not an acceptable clinical consultation (empty = ok).

    The approved generator is a small model (gemma-4-e2b), so the filter is strict:
    off-format, looping, non-clinical, non-English or self-describing output is dropped.
    """
    issues: list[str] = []
    lines = [line for line in text.split("\n") if line.strip()]
    labelled = [line for line in lines if _LABEL_RE.match(line)]
    speakers = Counter(line.split(":", 1)[0] for line in labelled)
    if (
        len(labelled) < 12
        or len(labelled) < 0.9 * len(lines)
        or "Doctor" not in speakers
        or not ({"Patient", "Caregiver"} & set(speakers))
        or speakers.get("Attachment", 0) > 0.6 * len(labelled)
        or max((len(line) for line in lines), default=0) > 900
    ):
        issues.append("off_format")
    bodies = [line.split(":", 1)[-1].strip().lower() for line in lines]
    repeats = Counter(bodies)
    if repeats and (repeats.most_common(1)[0][1] >= 3 or 1 - len(repeats) / len(bodies) > 0.15):
        issues.append("repetition")
    low = text.lower()
    if sum(term in low for term in _CLINICAL_TERMS) < 6:
        issues.append("non_clinical")
    letters = [ch for ch in text if ch.isalpha()]
    if letters and sum(not ch.isascii() for ch in letters) / len(letters) > 0.02:
        issues.append("non_english")
    if _META_RE.search(text):
        issues.append("meta_commentary")
    if is_ai_directed(text):
        issues.append("ai_directed")
    return issues


